const { chromium } = require("playwright");
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const errs = [];
  p.on("console", (m) => { if (m.type() === "error") errs.push(m.text().slice(0, 200)); });
  p.on("pageerror", (e) => errs.push("pageerror " + e));
  await p.goto("http://localhost:3000/", { waitUntil: "networkidle" });
  await p.waitForSelector("html.sc-ready");
  await p.evaluate(() => scrollTo({ top: 3000, behavior: "instant" }));
  await p.waitForTimeout(500);
  console.log("home instances", await p.evaluate(() => window.ScrollCraft.instances.length), await p.evaluate(() => document.documentElement.className));
  await p.click('header a[href="/faq"]');
  await p.waitForURL("**/faq");
  await p.waitForTimeout(1500);
  console.log("faq instances", await p.evaluate(() => (window.ScrollCraft ? window.ScrollCraft.instances.length : "n/a")), await p.evaluate(() => document.documentElement.className), await p.evaluate(() => document.documentElement.getAttribute("style")));
  await p.goBack();
  await p.waitForSelector(".tl");
  await p.waitForTimeout(2000);
  console.log("back instances", await p.evaluate(() => window.ScrollCraft.instances.length), await p.evaluate(() => document.documentElement.className));
  await p.evaluate(() => scrollTo({ top: 4800, behavior: "instant" }));
  await p.waitForTimeout(600);
  console.log("state", await p.evaluate(() => document.querySelector("[data-tl-peak]").getAttribute("data-sc-verify-state")));
  await p.click('header a[href="/en"]').catch(() => {});
  await p.waitForTimeout(2500);
  console.log("en", p.url(), await p.evaluate(() => window.ScrollCraft.instances.length), await p.evaluate(() => document.querySelector("h1")?.textContent));
  console.log("errors:", errs.join("\n"));
  await b.close();
})();
